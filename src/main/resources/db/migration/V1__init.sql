-- V1: baseline schema (venues, shows, users, seats, bookings).
-- Never edit this file once it has run anywhere: schema changes go in a new V2__...sql.

CREATE TABLE venues (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(100) NOT NULL,
    city    VARCHAR(50)  NOT NULL,
    address VARCHAR(255)
);

CREATE TABLE shows (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id   BIGINT                      NOT NULL,
    title      VARCHAR(150)                NOT NULL,
    start_time TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    price      NUMERIC(10, 2)              NOT NULL,
    CONSTRAINT fk_shows_venue FOREIGN KEY (venue_id) REFERENCES venues (id)
);
-- "Shows at this venue" (GET /api/shows?venueId=) and the FK check when deleting a venue
CREATE INDEX idx_shows_venue ON shows (venue_id);

CREATE TABLE users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)                NOT NULL,
    email      VARCHAR(255)                NOT NULL,
    password   VARCHAR(255)                NOT NULL,
    role       VARCHAR(20)                 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE seats (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id     BIGINT      NOT NULL,
    seat_number VARCHAR(10) NOT NULL,
    status      VARCHAR(20) NOT NULL,
    version     BIGINT      NOT NULL,
    CONSTRAINT fk_seats_show FOREIGN KEY (show_id) REFERENCES shows (id),
    CONSTRAINT uk_seats_show_seat_number UNIQUE (show_id, seat_number),
    CONSTRAINT ck_seats_status CHECK (status IN ('AVAILABLE', 'BOOKED'))
);

CREATE TABLE bookings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT                      NOT NULL,
    show_id      BIGINT                      NOT NULL,
    status       VARCHAR(20)                 NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    cancelled_at TIMESTAMP(6) WITH TIME ZONE,
    version      BIGINT                      NOT NULL,
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_bookings_show FOREIGN KEY (show_id) REFERENCES shows (id),
    CONSTRAINT ck_bookings_status CHECK (status IN ('CONFIRMED', 'CANCELLED'))
);
CREATE INDEX idx_bookings_user ON bookings (user_id);

CREATE TABLE booking_seats (
    booking_id BIGINT NOT NULL,
    seat_id    BIGINT NOT NULL,
    CONSTRAINT pk_booking_seats PRIMARY KEY (booking_id, seat_id),
    CONSTRAINT fk_booking_seats_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT fk_booking_seats_seat FOREIGN KEY (seat_id) REFERENCES seats (id)
);
-- "Which bookings include this seat?" would otherwise scan the whole table
CREATE INDEX idx_booking_seats_seat ON booking_seats (seat_id);
