-- V20: reviews by people who went to a show: a rating from 1 to 5 and an optional text, one per person per show.
-- Deleted with their show or their account.
CREATE TABLE reviews (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id    BIGINT                      NOT NULL,
    user_id    BIGINT                      NOT NULL,
    rating     INT                         NOT NULL,
    body       VARCHAR(1000),
    hidden     BOOLEAN                     NOT NULL DEFAULT FALSE, -- by an admin: not listed, not in the average
    hidden_at  TIMESTAMP(6) WITH TIME ZONE,
    hidden_by  BIGINT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reviews_show_user UNIQUE (show_id, user_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_reviews_body CHECK (body IS NULL OR char_length(body) BETWEEN 1 AND 1000),
    CONSTRAINT fk_reviews_show FOREIGN KEY (show_id) REFERENCES shows (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
-- A show's page lists its visible reviews, newest first
CREATE INDEX idx_reviews_show_visible ON reviews (show_id, created_at DESC) WHERE NOT hidden;
CREATE INDEX idx_reviews_user ON reviews (user_id);

-- Each show keeps the sum and count of its visible ratings, changed by the same transaction as the review (an
-- atomic "+ delta" UPDATE), so listings show the average without a query per show. The CHECK keeps them honest.
ALTER TABLE shows ADD COLUMN rating_count INT NOT NULL DEFAULT 0;
ALTER TABLE shows ADD COLUMN rating_sum INT NOT NULL DEFAULT 0;
ALTER TABLE shows ADD CONSTRAINT ck_shows_rating
    CHECK (rating_count >= 0 AND rating_sum BETWEEN rating_count AND 5 * rating_count);

-- "How was it?" emails: set once a booking has been looked at by the job, so nobody is asked twice
