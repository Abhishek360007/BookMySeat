-- V8: transactional outbox for emails. A row is written in the same transaction as the change it reports
-- (a booking, a cancellation...), so an email exists if and only if that change committed. A job then
-- delivers PENDING rows, retrying failures with backoff; after too many failures a row becomes FAILED.
CREATE TABLE email_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind            VARCHAR(40)                 NOT NULL,
    recipient       VARCHAR(255)                NOT NULL,
    subject         VARCHAR(255)                NOT NULL,
    body_text       TEXT                        NOT NULL,
    body_html       TEXT                        NOT NULL,
    status          VARCHAR(20)                 NOT NULL,
    attempts        INT                         NOT NULL,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_error      VARCHAR(500),
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    sent_at         TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT ck_email_outbox_status CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);
-- The job only ever looks for PENDING rows that are due
CREATE INDEX idx_email_outbox_due ON email_outbox (next_attempt_at) WHERE status = 'PENDING';
