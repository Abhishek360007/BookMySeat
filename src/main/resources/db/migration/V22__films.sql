-- V22: films. A film groups its shows (screenings): its title, runtime and details live once, and its reviews and
-- rating count for every screening. Existing shows get one film per title (ignoring case), runtime 180 minutes
-- (what the calendar event and the review emails assumed until now).
CREATE TABLE films (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(150)                NOT NULL,
    synopsis        VARCHAR(2000),
    runtime_minutes INT                         NOT NULL DEFAULT 180,
    language        VARCHAR(40),
    certificate     VARCHAR(4),
    rating_sum      INT                         NOT NULL DEFAULT 0,
    rating_count    INT                         NOT NULL DEFAULT 0,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_films_runtime CHECK (runtime_minutes BETWEEN 1 AND 600),
    CONSTRAINT ck_films_certificate CHECK (certificate IS NULL OR certificate IN ('U', 'UA', 'A', 'S')),
    CONSTRAINT ck_films_rating CHECK (rating_count >= 0 AND rating_sum BETWEEN rating_count AND 5 * rating_count)
);
-- One film per title whatever the case: "Dune" and "DUNE" are the same film (a remake gets a year: "Dune (2021)")
CREATE UNIQUE INDEX uk_films_title ON films (lower(title));

INSERT INTO films (title)
SELECT DISTINCT ON (lower(title)) title FROM shows ORDER BY lower(title), id;

ALTER TABLE shows ADD COLUMN film_id BIGINT;
UPDATE shows s SET film_id = f.id FROM films f WHERE lower(f.title) = lower(s.title);
ALTER TABLE shows ALTER COLUMN film_id SET NOT NULL;
ALTER TABLE shows ADD CONSTRAINT fk_shows_film FOREIGN KEY (film_id) REFERENCES films (id);
CREATE INDEX idx_shows_film ON shows (film_id, start_time);
-- A show's title is its film's (kept on the show for everything that already reads it)
UPDATE shows s SET title = f.title FROM films f WHERE f.id = s.film_id AND s.title <> f.title;

-- Reviews belong to the film now: one per person per film, whichever screening they went to (show_id stays: the
-- screening that let them review). Where someone reviewed two screenings of one film, the newest review stays.
ALTER TABLE reviews ADD COLUMN film_id BIGINT;
UPDATE reviews r SET film_id = s.film_id FROM shows s WHERE s.id = r.show_id;
DELETE FROM reviews r USING reviews newer
WHERE newer.film_id = r.film_id AND newer.user_id = r.user_id AND newer.id > r.id;
ALTER TABLE reviews ALTER COLUMN film_id SET NOT NULL;
ALTER TABLE reviews ADD CONSTRAINT fk_reviews_film FOREIGN KEY (film_id) REFERENCES films (id) ON DELETE CASCADE;
ALTER TABLE reviews DROP CONSTRAINT uk_reviews_show_user;
ALTER TABLE reviews ADD CONSTRAINT uk_reviews_film_user UNIQUE (film_id, user_id);
DROP INDEX idx_reviews_show_visible;
CREATE INDEX idx_reviews_film_visible ON reviews (film_id, created_at DESC) WHERE NOT hidden;

-- The rating moves to the film, counted from the reviews themselves
UPDATE films f SET rating_sum = x.total, rating_count = x.reviews
FROM (SELECT film_id, SUM(rating) AS total, COUNT(*) AS reviews FROM reviews WHERE NOT hidden GROUP BY film_id) x
WHERE x.film_id = f.id;

