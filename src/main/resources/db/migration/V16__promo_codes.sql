-- V16: promo codes created by admins. A code takes a percentage (optionally capped) or a flat amount off a booking's
-- total. Limits: a validity window, a minimum total, one show only, total uses and uses per person.
CREATE TABLE promo_codes (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(20)                 NOT NULL,
    description       VARCHAR(100),
    kind              VARCHAR(10)                 NOT NULL,
    amount            NUMERIC(10, 2)              NOT NULL,
    max_discount      NUMERIC(10, 2),
    min_total         NUMERIC(10, 2),
    show_id           BIGINT,
    valid_from        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    valid_until       TIMESTAMP(6) WITH TIME ZONE,
    max_uses          INT,
    max_uses_per_user INT                         NOT NULL,
    uses              INT                         NOT NULL DEFAULT 0,
    active            BOOLEAN                     NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version           BIGINT                      NOT NULL,
    -- Codes are stored in capitals; customers may type them in any case
    CONSTRAINT uk_promo_codes_code UNIQUE (code),
    CONSTRAINT ck_promo_codes_code CHECK (code ~ '^[A-Z0-9-]{3,20}$'),
    CONSTRAINT ck_promo_codes_kind CHECK (kind IN ('PERCENT', 'FLAT')),
    CONSTRAINT ck_promo_codes_amount CHECK (amount > 0 AND (kind = 'FLAT' OR amount <= 100)),
    CONSTRAINT ck_promo_codes_max_discount CHECK (max_discount IS NULL OR max_discount > 0),
    CONSTRAINT ck_promo_codes_min_total CHECK (min_total IS NULL OR min_total >= 0),
    CONSTRAINT ck_promo_codes_window CHECK (valid_until IS NULL OR valid_until > valid_from),
    CONSTRAINT ck_promo_codes_max_uses CHECK (max_uses IS NULL OR max_uses > 0),
    CONSTRAINT ck_promo_codes_per_user CHECK (max_uses_per_user > 0),
    -- The last line of defence for the limit: the database refuses a use beyond it
    CONSTRAINT ck_promo_codes_uses CHECK (uses >= 0 AND (max_uses IS NULL OR uses <= max_uses)),
    CONSTRAINT fk_promo_codes_show FOREIGN KEY (show_id) REFERENCES shows (id) ON DELETE CASCADE
);
CREATE INDEX idx_promo_codes_show ON promo_codes (show_id);
