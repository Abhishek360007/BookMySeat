-- V15: waitlist for sold-out shows. People join in order; when a booking is cancelled, the first one whose
-- request fits gets the freed seats held for a limited time (an offer). Entries are kept after they end
-- (CLAIMED, EXPIRED, LEFT, CLOSED), so the line and its history can be explained afterwards.
CREATE TABLE waitlist_entries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id          BIGINT                      NOT NULL,
    user_id          BIGINT                      NOT NULL,
    seats_wanted     INT                         NOT NULL,
    status           VARCHAR(20)                 NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    offered_at       TIMESTAMP(6) WITH TIME ZONE,
    offer_expires_at TIMESTAMP(6) WITH TIME ZONE,
    ended_at         TIMESTAMP(6) WITH TIME ZONE,
    version          BIGINT                      NOT NULL,
    CONSTRAINT fk_waitlist_show FOREIGN KEY (show_id) REFERENCES shows (id) ON DELETE CASCADE,
    CONSTRAINT fk_waitlist_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_waitlist_seats CHECK (seats_wanted BETWEEN 1 AND 6),
    CONSTRAINT ck_waitlist_status CHECK (status IN ('WAITING', 'OFFERED', 'CLAIMED', 'EXPIRED', 'LEFT', 'CLOSED'))
);
-- One place in line per person and show (ended entries don't count, so leaving and joining again works)
CREATE UNIQUE INDEX uk_waitlist_active ON waitlist_entries (show_id, user_id) WHERE status IN ('WAITING', 'OFFERED');
-- The line of a show, in order
CREATE INDEX idx_waitlist_line ON waitlist_entries (show_id, status, id);
CREATE INDEX idx_waitlist_user ON waitlist_entries (user_id);

-- The seats held for an offer
CREATE TABLE waitlist_offer_seats (
    entry_id BIGINT NOT NULL,
    seat_id  BIGINT NOT NULL,
    CONSTRAINT pk_waitlist_offer_seats PRIMARY KEY (entry_id, seat_id),
    CONSTRAINT fk_waitlist_offer_entry FOREIGN KEY (entry_id) REFERENCES waitlist_entries (id) ON DELETE CASCADE,
    CONSTRAINT fk_waitlist_offer_seat FOREIGN KEY (seat_id) REFERENCES seats (id) ON DELETE CASCADE
);
