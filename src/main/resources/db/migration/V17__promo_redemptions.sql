-- V17: promo codes on bookings. The booking keeps what was taken off and which code did it (a snapshot, like its
-- total: changing or switching off the code later doesn't touch it). total_amount stays what the customer pays.
ALTER TABLE bookings ADD COLUMN discount_amount NUMERIC(10, 2) NOT NULL DEFAULT 0;
ALTER TABLE bookings ADD COLUMN promo_code VARCHAR(20);
ALTER TABLE bookings ADD CONSTRAINT ck_bookings_discount CHECK (discount_amount >= 0);

-- Each use of a code. REDEEMED: a booking has it; RELEASED: that booking was cancelled, so the use was given back.
-- Kept after release, so a code's history can be explained.
CREATE TABLE promo_redemptions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promo_code_id BIGINT                      NOT NULL,
    user_id       BIGINT                      NOT NULL,
    booking_id    BIGINT,
    status        VARCHAR(20)                 NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    released_at   TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_promo_redemptions_code FOREIGN KEY (promo_code_id) REFERENCES promo_codes (id) ON DELETE CASCADE,
    CONSTRAINT fk_promo_redemptions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_promo_redemptions_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT uk_promo_redemptions_booking UNIQUE (booking_id),
    CONSTRAINT ck_promo_redemptions_status CHECK (status IN ('REDEEMED', 'RELEASED'))
);
-- How often a person has used a code (the per-person limit)
CREATE INDEX idx_promo_redemptions_code_user ON promo_redemptions (promo_code_id, user_id, status);
