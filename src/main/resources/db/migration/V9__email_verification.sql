-- V9: email verification. Verification is optional (nothing is blocked); users.email_verified_at records it.
ALTER TABLE users ADD COLUMN email_verified_at TIMESTAMP(6) WITH TIME ZONE;

-- Accounts from before verification existed (the admin, the demo account) count as verified
UPDATE users SET email_verified_at = created_at;

-- Single-use links. Like refresh tokens, only a SHA-256 hash of each token is stored.
CREATE TABLE email_verification_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                      NOT NULL,
    token_hash VARCHAR(64)                 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_email_verification_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_email_verification_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_email_verification_tokens_user ON email_verification_tokens (user_id);
