-- V6: online payments (Razorpay). One row per checkout (one Razorpay order).
-- Status flow: PENDING -> CONFIRMED | EXPIRED | REFUND_PENDING -> REFUNDED
-- (a confirmed booking that is cancelled later also goes REFUND_PENDING -> REFUNDED)

CREATE TABLE payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT                      NOT NULL,
    show_id        BIGINT                      NOT NULL,
    order_id       VARCHAR(64)                 NOT NULL,
    payment_id     VARCHAR(64),
    amount         NUMERIC(10, 2)              NOT NULL,
    currency       VARCHAR(3)                  NOT NULL,
    status         VARCHAR(20)                 NOT NULL,
    booking_id     BIGINT,
    refund_id      VARCHAR(64),
    failure_reason VARCHAR(255),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version        BIGINT                      NOT NULL,
    CONSTRAINT fk_payments_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_payments_show FOREIGN KEY (show_id) REFERENCES shows (id),
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    -- One payment per Razorpay order, one booking per payment: the database itself prevents double confirms
    CONSTRAINT uk_payments_order UNIQUE (order_id),
    CONSTRAINT uk_payments_payment UNIQUE (payment_id),
    CONSTRAINT uk_payments_booking UNIQUE (booking_id),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'CONFIRMED', 'EXPIRED', 'REFUND_PENDING', 'REFUNDED')),
    CONSTRAINT ck_payments_amount CHECK (amount > 0)
);
-- The expiry job looks for PENDING payments past their deadline
CREATE INDEX idx_payments_status_expires ON payments (status, expires_at);
CREATE INDEX idx_payments_user ON payments (user_id);

CREATE TABLE payment_seats (
    payment_id BIGINT NOT NULL,
    seat_id    BIGINT NOT NULL,
    CONSTRAINT pk_payment_seats PRIMARY KEY (payment_id, seat_id),
    CONSTRAINT fk_payment_seats_payment FOREIGN KEY (payment_id) REFERENCES payments (id) ON DELETE CASCADE,
    CONSTRAINT fk_payment_seats_seat FOREIGN KEY (seat_id) REFERENCES seats (id) ON DELETE CASCADE
);
